"""Station closures: window rules, per-station effect and the public contract.

The effect rules are shared by the server projector, Kotlin StationClosures,
Swift StationClosures and the web client. The golden cases live in
fixtures/closures/effect.json (generated by scripts/generate-302-fixtures.py);
tests/test_closures.py asserts every case against closure_effect() below, so a
change here that drifts from the clients fails the suite.

Closures in this module are plain dicts in the fixture shape:

    {"id", "stationIds", "lineIds", "mode", "startsAtEpochSeconds",
     "endsAtEpochSeconds", "status"}

load_closures() reads them from the station_closures table (migration 0029)
and public_payload() renders GET /api/closures.
"""
from __future__ import annotations

import hashlib
import json
import sqlite3
import time
from datetime import datetime, timezone

MODES = ("closed", "pass_through", "exit_only", "entry_only")
# Most restrictive first; used to pick the reported mode and the primary closure.
MODE_ORDER = list(MODES)
STATUSES = ("draft", "scheduled", "active", "ended", "cancelled")
INACTIVE_STATUSES = ("draft", "cancelled")
LANGS = ("en", "el", "sq", "it")
UPCOMING_WINDOW_SECONDS = 24 * 3600
# GET /api/closures keeps ended closures for a day so a client that was offline
# overnight still sees why a station was closed.
PUBLIC_GRACE_SECONDS = 24 * 3600
SCHEMA_VERSION = 1


# ---------------------------------------------------------------------------
# Window + effect (must match fixtures/closures/effect.json)
# ---------------------------------------------------------------------------

def closure_is_active(c: dict, now: int) -> bool:
    if c.get("status") in INACTIVE_STATUSES:
        return False
    if now < c["startsAtEpochSeconds"]:
        return False
    ends = c.get("endsAtEpochSeconds")
    return ends is None or now < ends


def closure_applies(c: dict, station_id: str, line_id: str | None) -> bool:
    if station_id not in c["stationIds"]:
        return False
    lines = c.get("lineIds") or []
    return not lines or line_id is None or line_id in lines


def closure_effect(closures: list[dict], station_id: str, line_id: str | None, now: int) -> dict:
    """Effect of every closure on one (station, line) at epoch second `now`.

    line_id None means "any line at this station". Returns the fixture's
    expected shape: active, mode, canBoard, canAlight, closureId,
    endsAtEpochSeconds, upcomingClosureId, upcomingStartsAtEpochSeconds.
    """
    active = [c for c in closures if closure_applies(c, station_id, line_id) and closure_is_active(c, now)]
    if not active:
        upcoming = [
            c for c in closures
            if closure_applies(c, station_id, line_id)
            and c.get("status") not in INACTIVE_STATUSES
            and now < c["startsAtEpochSeconds"] <= now + UPCOMING_WINDOW_SECONDS
        ]
        upcoming.sort(key=lambda c: (c["startsAtEpochSeconds"], c["id"]))
        return {
            "active": False, "mode": None, "canBoard": True, "canAlight": True,
            "closureId": None, "endsAtEpochSeconds": None,
            "upcomingClosureId": upcoming[0]["id"] if upcoming else None,
            "upcomingStartsAtEpochSeconds": upcoming[0]["startsAtEpochSeconds"] if upcoming else None,
        }
    can_board = all(c["mode"] == "entry_only" for c in active)
    can_alight = all(c["mode"] == "exit_only" for c in active)
    if not can_board and not can_alight:
        modes = {c["mode"] for c in active}
        mode = next(m for m in MODE_ORDER if m in modes)
        if mode in ("exit_only", "entry_only"):
            mode = "closed"  # exit_only + entry_only together leave nothing open
    else:
        mode = active[0]["mode"]
    active.sort(key=lambda c: (MODE_ORDER.index(c["mode"]), c["id"]))
    primary = active[0]
    # Any open-ended closure means "until further notice", else the latest end.
    ends = [c.get("endsAtEpochSeconds") for c in active]
    ends_at = None if any(e is None for e in ends) else max(ends)
    return {
        "active": True, "mode": mode, "canBoard": can_board, "canAlight": can_alight,
        "closureId": primary["id"], "endsAtEpochSeconds": ends_at,
        "upcomingClosureId": None, "upcomingStartsAtEpochSeconds": None,
    }


def status_for_window(c: dict, now: int) -> str:
    """Status the dispatcher should store for a non-draft, non-cancelled closure."""
    if c.get("status") in INACTIVE_STATUSES:
        return c["status"]
    ends = c.get("endsAtEpochSeconds")
    if ends is not None and now >= ends:
        return "ended"
    if now >= c["startsAtEpochSeconds"]:
        return "active"
    return "scheduled"


# ---------------------------------------------------------------------------
# Storage
# ---------------------------------------------------------------------------

def _json_list(raw: str | None) -> list[str]:
    try:
        value = json.loads(raw or "[]")
    except (TypeError, ValueError):
        return []
    return [str(v) for v in value] if isinstance(value, list) else []


def row_to_closure(row: sqlite3.Row) -> dict:
    """A station_closures row in the fixture shape (plus storage extras)."""
    return {
        "id": row["id"],
        "stationIds": _json_list(row["station_ids"]),
        "lineIds": _json_list(row["line_ids"]),
        "mode": row["mode"],
        "startsAtEpochSeconds": int(row["starts_at"]),
        "endsAtEpochSeconds": int(row["ends_at"]) if row["ends_at"] is not None else None,
        "status": row["status"],
    }


def load_closures(conn: sqlite3.Connection, *, include_drafts: bool = False) -> list[dict]:
    """Closures that can affect service, in the fixture shape.

    Returns [] on a database that predates migration 0029, so the projector
    keeps working on a Pi that has not migrated yet.
    """
    sql = "SELECT * FROM station_closures"
    if not include_drafts:
        sql += " WHERE status NOT IN ('draft', 'cancelled')"
    try:
        rows = conn.execute(sql + " ORDER BY starts_at, id").fetchall()
    except sqlite3.OperationalError:
        return []
    return [row_to_closure(r) for r in rows]


def localized(row: sqlite3.Row | dict, prefix: str) -> dict:
    """{"en": ..., "el": ...} from prefix_en/prefix_el/... columns, empty ones omitted."""
    out = {}
    for lang in LANGS:
        value = row[f"{prefix}_{lang}"] if f"{prefix}_{lang}" in row.keys() else None
        if value:
            out[lang] = value
    return out


def iso_utc(epoch: int | None) -> str | None:
    if epoch is None:
        return None
    return datetime.fromtimestamp(int(epoch), tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _replacement_bus(raw: str | None) -> dict | None:
    if not raw:
        return None
    try:
        bus = json.loads(raw)
    except (TypeError, ValueError):
        return None
    if not isinstance(bus, dict):
        return None
    return {
        "label": bus.get("label") or {},
        "fromStop": bus.get("fromStop") or {},
        "toStop": bus.get("toStop") or {},
        "headwayMinutes": bus.get("headwayMinutes"),
        "stops": bus.get("stops") or [],
    }


def serialize(row: sqlite3.Row) -> dict:
    """One station_closures row in the GET /api/closures contract shape."""
    starts = int(row["starts_at"])
    ends = int(row["ends_at"]) if row["ends_at"] is not None else None
    return {
        "id": row["id"],
        "stationIds": _json_list(row["station_ids"]),
        "lineIds": _json_list(row["line_ids"]),
        "mode": row["mode"],
        "startsAt": iso_utc(starts),
        "startsAtEpochSeconds": starts,
        "endsAt": iso_utc(ends),
        "endsAtEpochSeconds": ends,
        "status": row["status"],
        "reason": localized(row, "reason"),
        "replacementBus": _replacement_bus(row["replacement_bus"]),
        "source": row["source"],
    }


def public_closures(conn: sqlite3.Connection, now: int | None = None) -> list[dict]:
    """Non-draft, non-cancelled closures whose end is open or later than now - 24 h."""
    if now is None:
        now = int(time.time())
    try:
        rows = conn.execute(
            "SELECT * FROM station_closures"
            " WHERE status NOT IN ('draft', 'cancelled')"
            " AND (ends_at IS NULL OR ends_at > ?)"
            " ORDER BY starts_at, id",
            (now - PUBLIC_GRACE_SECONDS,),
        ).fetchall()
    except sqlite3.OperationalError:
        return []
    return [serialize(r) for r in rows]


def public_payload(conn: sqlite3.Connection, now: int | None = None) -> tuple[dict, str]:
    """(GET /api/closures body, ETag). The ETag covers the closures only, not
    generatedAt, so an unchanged list revalidates with 304."""
    if now is None:
        now = int(time.time())
    closures = public_closures(conn, now)
    return (
        {"schemaVersion": SCHEMA_VERSION, "generatedAt": iso_utc(now), "closures": closures},
        etag_for(closures),
    )


def seed_payload(closures: list[dict]) -> dict:
    """Bundled seed shape (closures.json): the contract without generatedAt, so
    the file bytes, and therefore its manifest hash, only change with content."""
    return {"schemaVersion": SCHEMA_VERSION, "closures": closures}


def canonical_bytes(payload: object) -> bytes:
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def etag_for(payload: object) -> str:
    return '"' + hashlib.sha256(canonical_bytes(payload)).hexdigest()[:32] + '"'


def flip_statuses(conn: sqlite3.Connection, now: int | None = None) -> dict[str, int]:
    """scheduled -> active -> ended by time. Returns how many rows moved."""
    if now is None:
        now = int(time.time())
    ended = conn.execute(
        "UPDATE station_closures SET status='ended',"
        " updated_at=strftime('%Y-%m-%dT%H:%M:%SZ','now')"
        " WHERE status IN ('scheduled', 'active') AND ends_at IS NOT NULL AND ends_at <= ?",
        (now,),
    ).rowcount
    activated = conn.execute(
        "UPDATE station_closures SET status='active',"
        " updated_at=strftime('%Y-%m-%dT%H:%M:%SZ','now')"
        " WHERE status='scheduled' AND starts_at <= ? AND (ends_at IS NULL OR ends_at > ?)",
        (now, now),
    ).rowcount
    return {"activated": activated, "ended": ended}

def _bind(stations: list[str], times: list[str | None]) -> list[tuple[str, str]]:
    """Pair a stop time with its station, skipping blanks (train doesn't
    stop there)."""
    if len(times) != len(stations):
        raise ValueError(
            f"length mismatch: {len(stations)} stations vs {len(times)} times"
        )
    return [(sid, hhmm) for sid, hhmm in zip(stations, times) if hhmm]



def _expand(line_id: str, direction: str, day_types: list[str],
            stations: list[str], trips: list[tuple],
            skip_on_weekend: set[str] | None = None,
            service_label: str | None = None) -> list[tuple]:
    """Build (trip_rows, stop_rows) for inserting."""
    trip_rows: list[tuple] = []
    stop_rows: list[tuple] = []
    for dt in day_types:
        for train_no, times in trips:
            if skip_on_weekend and dt in ("sat", "sun") and train_no in skip_on_weekend:
                continue
            stops = _bind(stations, list(times))
            if not stops:
                continue
            trip_rows.append((train_no, line_id, direction, dt, service_label))
            for seq, (sid, hhmm) in enumerate(stops):
                stop_rows.append((train_no, line_id, direction, dt, sid, seq, hhmm))
    return trip_rows, stop_rows


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--apply", action="store_true",
                   help="Write to DB (default is dry-run with summary)")
    args = p.parse_args()

    all_trips: list[tuple] = []
    all_stops: list[tuple] = []

    blocks = [
        # (line_id, direction, day_types, stations, trips, weekday_only_set)
        ("A1", "outbound", ["mon_thu", "fri"], A1_STATIONS_OUT, A1_OUT_MONFRI, None),
        ("A1", "inbound",  ["mon_thu", "fri"], A1_STATIONS_OUT, A1_IN_MONFRI,  None),
        ("A1", "outbound", ["sat", "sun"],     A1_STATIONS_OUT, A1_OUT_WEEKEND, None),
        ("A1", "inbound",  ["sat", "sun"],     A1_STATIONS_OUT, A1_IN_WEEKEND,  None),
        ("A2", "outbound", ["mon_thu", "fri"], A2_STATIONS_OUT, A2_OUT_MONFRI, None),
        ("A2", "inbound",  ["mon_thu", "fri"], A2_STATIONS_OUT, A2_IN_MONFRI,  None),
        ("A2", "outbound", ["sat", "sun"],     A2_STATIONS_OUT, A2_OUT_WEEKEND, None),
        ("A2", "inbound",  ["sat", "sun"],     A2_STATIONS_OUT, A2_IN_WEEKEND,  None),
        ("A3", "outbound", ["mon_thu", "fri", "sat", "sun"], A3_STATIONS_OUT, A3_OUT_DAILY, A3_OUT_WEEKDAY_ONLY),
        ("A3", "inbound",  ["mon_thu", "fri", "sat", "sun"], A3_STATIONS_OUT, A3_IN_DAILY,  A3_IN_WEEKDAY_ONLY),
        ("A4", "outbound", ["mon_thu", "fri", "sat", "sun"], A4_STATIONS_OUT, A4_OUT_DAILY, None),
        ("A4", "inbound",  ["mon_thu", "fri", "sat", "sun"], A4_STATIONS_OUT, A4_IN_DAILY,  None),
    ]

    for line_id, direction, day_types, stations, trips, weekday_only in blocks:
        t_rows, s_rows = _expand(line_id, direction, day_types, stations, trips,
                                  skip_on_weekend=weekday_only)
        all_trips.extend(t_rows)
        all_stops.extend(s_rows)

    print(f"Will write {len(all_trips)} trip rows + {len(all_stops)} stop rows")

    if not args.apply:
        print("Dry-run. Pass --apply to write to the database.")
        return

    with dbmod.connect() as conn:
        dbmod.migrate(conn)
        cur = conn.cursor()
        cur.execute("BEGIN")
        try:
            cur.execute("DELETE FROM scheduled_trip_stops")
            cur.execute("DELETE FROM scheduled_trips")
            cur.executemany(
                "INSERT INTO scheduled_trips"
                "(train_no, line_id, direction, day_type, service_label)"
                " VALUES(?,?,?,?,?)",
                all_trips,
            )
            cur.executemany(
                "INSERT INTO scheduled_trip_stops"
                "(train_no, line_id, direction, day_type, station_id, stop_sequence, departure_time)"
                " VALUES(?,?,?,?,?,?,?)",
                all_stops,
            )
            cur.execute("COMMIT")
            print(f"Inserted {len(all_trips)} trips, {len(all_stops)} stops.")
        except Exception:
            cur.execute("ROLLBACK")
            raise


if __name__ == "__main__":
    main()
